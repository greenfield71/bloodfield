# CTF Known MBA Identities Dictionary
# ==============================================================================

CTF_MBA_IDENTITIES = {
    "(x ^ y) + 2*(x & y)": "x + y",
    "(x | y) + (x & y)": "x + y",
    "(x | y) - (x & ~y)": "y",
    "(x | y) - (~x & y)": "x",
    "(x ^ y) - 2*(~x & y)": "x - y",
    "(x | y) - (x ^ y)": "x & y",
    "(x & ~y) + (x & y)": "x",
    "(x & y) - (x | y)": "-(x ^ y)",
    "(x ^ ~y) + 2*(x | y)": "x - y - 1",
}


def simplify_expression(expr_str: str) -> str:
    """Simplify an arithmetic-bitwise string expression using truth-table decomposition."""
    cleaned = expr_str.strip()

    # Detect variables present
    has_x = "x" in cleaned
    has_y = "y" in cleaned
    has_z = "z" in cleaned

    if has_z or (has_x and has_y and has_z):
        f = lambda x, y, z: parse_and_eval(cleaned, {"x": x, "y": y, "z": z})
        _, simplified = simplify_3var_mba(f)
        return simplified
    elif has_x and has_y:
        f = lambda x, y: parse_and_eval(cleaned, {"x": x, "y": y})
        _, simplified = simplify_2var_mba(f)
        return simplified
    elif has_x:
        f = lambda x, y: parse_and_eval(cleaned, {"x": x, "y": 0})
        _, simplified = simplify_2var_mba(f)
        return simplified
    elif has_y:
        f = lambda x, y: parse_and_eval(cleaned, {"x": 0, "y": y})
        _, simplified = simplify_2var_mba(f)
        return simplified
    else:
        # Constant expression
        val = parse_and_eval(cleaned, {})
        return str(val)


# ==============================================================================
# Z3 Formal Verification
# ==============================================================================

def verify_equivalence_z3(expr1_str: str, expr2_str: str, bit_width: int = 64) -> bool:
    """Use Z3 to formally verify that two bitvector expressions are equivalent."""
    if not Z3_AVAILABLE:
        print("[!] Z3 is not installed (`pip install --user z3-solver`). Skipping formal proof.")
        return True

    # Parse expressions into Z3 bitvector AST
    x = z3.BitVec("x", bit_width)
    y = z3.BitVec("y", bit_width)
    z = z3.BitVec("z", bit_width)
    env = {"x": x, "y": y, "z": z}

    def _to_z3(node: ast.AST) -> Any:
        if isinstance(node, ast.Constant):
            return z3.BitVecVal(node.value, bit_width)
        elif isinstance(node, ast.Name):
            return env[node.id]
        elif isinstance(node, ast.BinOp):
            l = _to_z3(node.left)
            r = _to_z3(node.right)
            if isinstance(node.op, ast.Add): return l + r
            if isinstance(node.op, ast.Sub): return l - r
            if isinstance(node.op, ast.Mult): return l * r
            if isinstance(node.op, ast.BitAnd): return l & r
            if isinstance(node.op, ast.BitOr): return l | r
            if isinstance(node.op, ast.BitXor): return l ^ r
        elif isinstance(node, ast.UnaryOp):
            operand = _to_z3(node.operand)
            if isinstance(node.op, ast.Invert): return ~operand
            if isinstance(node.op, ast.USub): return -operand
            if isinstance(node.op, ast.UAdd): return operand
        raise ValueError(f"Unsupported Z3 translation for node {type(node)}")

    z1 = _to_z3(ast.parse(expr1_str, mode="eval").body)
    z2 = _to_z3(ast.parse(expr2_str, mode="eval").body)

    solver = z3.Solver()
    solver.add(z1 != z2)
    result = solver.check()
    return result == z3.unsat


# ==============================================================================
# Self-Test Suite
# ==============================================================================

def run_tests() -> bool:
    print("[*] Running Mixed Boolean-Arithmetic (MBA) Deobfuscation Self-Tests...")

    # Test 1: Classic addition identity: (x ^ y) + 2*(x & y) == x + y
    expr1 = "(x ^ y) + 2 * (x & y)"
    res1 = simplify_expression(expr1)
    assert res1.replace(" ", "") in ("x+y", "y+x"), f"Test 1 Failed: {res1}"
    print(f"  [+] Test 1 Passed: '{expr1}' -> '{res1}'")

    # Test 2: Subtraction identity: (x | y) - (x & ~y) == y
    expr2 = "(x | y) - (x & ~y)"
    res2 = simplify_expression(expr2)
    assert res2 == "y", f"Test 2 Failed: {res2}"
    print(f"  [+] Test 2 Passed: '{expr2}' -> '{res2}'")

    # Test 3: Subtraction identity: (x ^ y) - 2*(~x & y) == x - y
    expr3 = "(x ^ y) - 2 * (~x & y)"
    res3 = simplify_expression(expr3)
    assert res3.replace(" ", "") in ("x-y",), f"Test 3 Failed: {res3}"
    print(f"  [+] Test 3 Passed: '{expr3}' -> '{res3}'")

    # Test 4: OR / AND combination: (x | y) + (x & y) == x + y
    expr4 = "(x | y) + (x & y)"
    res4 = simplify_expression(expr4)
    assert res4.replace(" ", "") in ("x+y", "y+x"), f"Test 4 Failed: {res4}"
    print(f"  [+] Test 4 Passed: '{expr4}' -> '{res4}'")

    # Test 5: 3-Variable Linear MBA: (x ^ y ^ z) + 2*(x & y) + 2*(x & z) + 2*(y & z) - 4*(x & y & z) == x + y + z
    expr5 = "(x ^ y ^ z) + 2*(x & y) + 2*(x & z) + 2*(y & z) - 4*(x & y & z)"
    res5 = simplify_expression(expr5)
    normalized5 = "".join(sorted(res5.replace(" ", "").split("+")))
    assert normalized5 == "xyz", f"Test 5 Failed: {res5}"
    print(f"  [+] Test 5 Passed: 3-variable MBA decomposition -> '{res5}'")

    # Test 6: Formal Z3 Equivalence Verification
    if Z3_AVAILABLE:
        proved = verify_equivalence_z3(expr1, "x + y", bit_width=64)
        assert proved, "Test 6 Failed: Z3 proof failed for Test 1"
        proved3 = verify_equivalence_z3(expr5, "x + y + z", bit_width=16)
        assert proved3, "Test 6 Failed: Z3 proof failed for Test 5"
        print("  [+] Test 6 Passed: Z3 formally proved bitvector integer equivalence (64-bit and 16-bit)")
    else:
        print("  [!] Z3 skipped (not installed).")

    print("[SUCCESS] All MBA deobfuscation tests passed cleanly!")
    return True


# ==============================================================================
# CLI Entrypoint
# ==============================================================================

def main() -> None:
    parser = argparse.ArgumentParser(description="Mixed Boolean-Arithmetic (MBA) Deobfuscator")
    parser.add_argument("--test", action="store_true", help="Run self-test suite")
    parser.add_argument("--expr", type=str, help="Expression to simplify (e.g. '(x ^ y) + 2*(x & y)')")
    parser.add_argument("--verify", action="store_true", help="Formally verify equivalence with Z3")

    parsed = parser.parse_args()

    if parsed.test or len(sys.argv) == 1:
        success = run_tests()
        sys.exit(0 if success else 1)

    if not parsed.expr:
        parser.error("--expr is required when not running --test.")

    simplified = simplify_expression(parsed.expr)
    print(f"[*] Input Expression : {parsed.expr}")
    print(f"[+] Simplified Form  : {simplified}")

    if parsed.verify:
        if Z3_AVAILABLE:
            equiv = verify_equivalence_z3(parsed.expr, simplified)
            status = "PROVED EQUIVALENT (unsat)" if equiv else "NOT EQUIVALENT"
            print(f"[*] Z3 Verification  : {status}")
        else:
            print("[!] Z3 not installed. Cannot run formal verification.")


if __name__ == "__main__":
    main()
